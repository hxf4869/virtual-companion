#!/usr/bin/env python3
"""Docker resource lifecycle helpers for the G12 harness (VC-R59).

Ownership contract: a resource is only ever removed when THIS run recorded
its exact identity at the moment of creation. The creation receipt is a
fresh per-invocation nonce, generated by run.sh and injected into the
rendered compose file as a label on every service (container), volume, and
network: only this invocation ever knew the nonce, so an object carrying
`vc.g12.nonce=<nonce>` is provably a product of this run's own create
action. run.sh proves the nonce-absent (rc 0, empty) before creating,
splits creation into `compose create` (nothing started) followed by an
immediate identity capture, and only then starts the stack — mid-creation
failures still leave the receipts received so far. The shared compose
project label, resource names, and pre/post diffs are NOT creator proofs:
they only gate the preflight (refuse collisions) and feed a read-only
leftover detector.

Removal re-verifies the current identity before touching anything —
containers by CID (immutable) plus recorded name, volumes by name +
driver + CreatedAt + nonce, networks by name + immutable Id — so a
same-name replacement is always preserved. Absence is proven only by a
successful daemon query that does not list the resource (rc 0, count 0);
a failed query keeps the item on the leftover list — a check error is
never treated as "gone", and a cleanup failure is never reported as clean.
No prefix/time-window/dangling heuristics, no prune, no --remove-orphans.

Query/removal logic lives here with docker_cli as the single seam (unit
tests stub it); run.sh is the only production caller.
"""

import argparse
import json
import os
import subprocess
import sys
import time

NONCE_LABEL = "vc.g12.nonce"
PROJECT_LABEL = "com.docker.compose.project"
# Bounded absence poll after stop/rm (--rm removal is asynchronous).
ABSENCE_POLLS = 20
ABSENCE_SLEEP_S = 0.5
RM_RETRIES = 3

# Optional wall-clock deadline covering every docker call of THIS process
# (VC-R79 TLS teardown): when set, each call gets the remaining time as its
# subprocess timeout and expiry raises TimeoutError — the CLI exits nonzero
# with the records kept, and subprocess.run kills/reaps the docker child so
# no cleanup CLI process is left behind. None (the default) preserves the
# G12 callers' original unbounded behavior.
_DEADLINE_MONO = None


def docker_cli(args):
    """One docker CLI invocation; rc is the caller's to interpret."""
    env = dict(os.environ)
    env.setdefault("DOCKER_CONTEXT", "orbstack")
    timeout = None
    if _DEADLINE_MONO is not None:
        remaining = _DEADLINE_MONO - time.monotonic()
        if remaining <= 0:
            raise TimeoutError("cleanup deadline exceeded before the docker "
                               f"call: docker {' '.join(args[:3])}")
        timeout = remaining
    try:
        return subprocess.run(["docker", *args], capture_output=True, text=True,
                              env=env, timeout=timeout)
    except subprocess.TimeoutExpired as exc:
        raise TimeoutError(f"docker {' '.join(args[:3])} exceeded the "
                           "cleanup deadline") from exc


def _inspect_first(args):
    proc = docker_cli(args)
    if proc.returncode != 0:
        return None
    try:
        return json.loads(proc.stdout)[0]
    except (json.JSONDecodeError, IndexError):
        return None


def _container_inspect(cid):
    return _inspect_first(["inspect", cid])


def _volume_inspect(name):
    return _inspect_first(["volume", "inspect", name])


def _network_inspect(name):
    return _inspect_first(["network", "inspect", name])


def _nonce_filter(nonce):
    return f"label={NONCE_LABEL}={nonce}"


def _label_query(kind, extra_filter=None):
    """(proc, names): listing query for containers/volumes/networks."""
    base = (["ps", "-aq"] if kind == "container" else
            [kind, "ls", "--format", "{{.Name}}"])
    return docker_cli([*base, "--filter", extra_filter])


def container_absent(cid):
    """(absent, note). Absent needs inspect rc!=0 AND a successful id-filter
    listing that comes back empty — a daemon query failure is not absence."""
    if _container_inspect(cid) is not None:
        return False, "inspect still resolves"
    listing = docker_cli(["ps", "-aq", "--filter", f"id={cid}"])
    if listing.returncode != 0:
        return False, f"id listing query failed rc={listing.returncode}"
    if listing.stdout.split():
        return False, "still listed by id filter"
    return True, ""


def _named_absent(kind, name):
    ls = docker_cli([kind, "ls", "--format", "{{.Name}}"])
    if ls.returncode != 0:
        return False, f"{kind} ls query failed rc={ls.returncode}"
    if name in ls.stdout.split():
        return False, f"{kind} {name} still listed"
    return True, ""


def volume_absent(name):
    return _named_absent("volume", name)


def network_absent(name):
    return _named_absent("network", name)


def tag_listed(ref):
    """True/False from a successful query; None when the query failed."""
    ls = docker_cli(["image", "ls", "--format", "{{.Repository}}:{{.Tag}}"])
    if ls.returncode != 0:
        return None
    return ref in ls.stdout.split()


def stop_remove_containers(entries):
    """Stop/rm only the recorded CIDs, after matching the recorded name.

    Removal is confirmed with a daemon-checked absence poll (bounded);
    anything not provably gone is returned as a leftover description.
    """
    leftovers = []
    for entry in entries:
        cid, name = entry["cid"], entry.get("name")
        current = _container_inspect(cid)
        if current is not None and name and \
                current.get("Name", "").lstrip("/") != name:
            leftovers.append(
                f"container {cid[:12]} identity changed: recorded {name!r}, "
                f"now {current.get('Name', '').lstrip('/')!r}; not removed")
            continue
        if current is not None:
            docker_cli(["stop", "-t", "5", cid])
            docker_cli(["rm", "-f", cid])
        absent, note = False, "not checked"
        for _ in range(ABSENCE_POLLS):
            absent, note = container_absent(cid)
            if absent:
                break
            time.sleep(ABSENCE_SLEEP_S)
        if not absent:
            leftovers.append(f"container {cid[:12]} ({name}) not proven "
                             f"gone: {note}")
    return leftovers


def _remove_named(kind, entries, expected_nonce):
    """Remove recorded volumes/networks whose CURRENT identity still equals
    the recorded one; same-name replacements are always preserved.

    A receipt is only actionable when it carries this run's nonce and a
    complete creation identity (volumes: driver + CreatedAt; networks:
    immutable Id). Unverified receipts (inspect failed, or the detail shows
    a different nonce — a replacement between listing and inspect) and any
    persisted record whose nonce does not match this run's are never
    removed, only reported.
    """
    leftovers = []
    for entry in entries:
        name = entry["name"]
        if entry.get("unverified") or entry.get("nonce") != expected_nonce:
            leftovers.append(
                f"{kind} {name} receipt unverified or nonce-mismatched; "
                "preserved, not removed")
            continue
        current = (_volume_inspect(name) if kind == "volume"
                   else _network_inspect(name))
        if current is not None:
            labels = current.get("Labels") or {}
            if kind == "volume":
                match = (labels.get(NONCE_LABEL) == entry.get("nonce")
                         and entry.get("driver") is not None
                         and current.get("Driver") == entry.get("driver")
                         and current.get("CreatedAt") == entry.get("created_at"))
            else:
                match = (labels.get(NONCE_LABEL) == entry.get("nonce")
                         and entry.get("id") is not None
                         and current.get("Id") == entry.get("id"))
            if not match:
                leftovers.append(
                    f"{kind} {name} current identity differs from the "
                    "creation record (or record lacks identity); replacement "
                    "preserved, not removed")
                continue
            absent = False
            for _ in range(RM_RETRIES):
                docker_cli([kind, "rm", name])
                absent, _ = _named_absent(kind, name)
                if absent:
                    break
                time.sleep(ABSENCE_SLEEP_S)
            if not absent:
                absent, note = _named_absent(kind, name)
                if not absent:
                    leftovers.append(f"{kind} {name} not proven gone: {note}")
        else:
            # inspect rc!=0 alone is not absence; prove it with a listing.
            absent, note = _named_absent(kind, name)
            if not absent:
                leftovers.append(f"{kind} {name} not proven gone: {note}")
    return leftovers


def capture_inventory(nonce, project):
    """Record exactly the objects carrying this run's nonce label right now.

    This is the creation-receipt capture, taken between `compose create`
    (nothing started) and `compose up` (start): every hit carries the fresh
    nonce only this invocation ever injected, so membership is this run's
    creation evidence — a concurrent creator on the same project label
    cannot appear here. A container whose inspect fails still records its
    CID (the nonce-labelled listing itself is the receipt); volumes and
    networks without a readable identity record it as null, which cleanup
    treats conservatively (preserve, never remove).
    """
    inv = {"project": project, "nonce": nonce, "containers": [],
           "volumes": [], "networks": []}
    ps = _label_query("container", _nonce_filter(nonce))
    if ps.returncode != 0:
        raise RuntimeError(f"nonce container query failed rc={ps.returncode}")
    for cid in ps.stdout.split():
        info = _container_inspect(cid)
        if info is None:
            inv["containers"].append({"cid": cid, "name": None})
            continue
        inv["containers"].append({
            "cid": info["Id"],
            "name": info.get("Name", "").lstrip("/"),
            "service": (info.get("Config", {}).get("Labels") or {})
                .get("com.docker.compose.service"),
            "mounts": info.get("Mounts", []),
            "networks": sorted((info.get("NetworkSettings", {})
                                .get("Networks") or {}).keys()),
            "image": info.get("Config", {}).get("Image"),
            "nonce": (info.get("Config", {}).get("Labels") or {})
                .get(NONCE_LABEL),
        })
    for kind in ("volume", "network"):
        ls = _label_query(kind, _nonce_filter(nonce))
        if ls.returncode != 0:
            raise RuntimeError(f"nonce {kind} query failed rc={ls.returncode}")
        for name in ls.stdout.split():
            info = (_volume_inspect(name) if kind == "volume"
                    else _network_inspect(name))
            if info is None:
                # identity unreadable: NOT a usable receipt — record it as
                # unverified so the start gate refuses and cleanup preserves
                inv[f"{kind}s"].append(
                    {"name": name,
                     "unverified": "identity unreadable at capture"})
                continue
            detail_nonce = (info.get("Labels") or {}).get(NONCE_LABEL)
            if detail_nonce != nonce:
                # the same-name object was replaced between the nonce listing
                # and this inspect: a foreign identity must never be promoted
                # into this run's receipt — keep the confirmed receipts and
                # flag this name as unverified, replacement preserved.
                inv[f"{kind}s"].append(
                    {"name": name,
                     "unverified": "detail nonce differs from this run's "
                                   "nonce (same-name replacement)"})
                continue
            if kind == "volume":
                inv["volumes"].append({
                    "name": name,
                    "driver": info.get("Driver"),
                    "created_at": info.get("CreatedAt"),
                    "nonce": detail_nonce,
                })
            else:
                inv["networks"].append({
                    "name": name,
                    "id": info.get("Id"),
                    "nonce": detail_nonce,
                })
    return inv


def require_absent(project, nonce, names, tags):
    """Preflight: prove every expected-absent resource is absent.

    rc0 queries only: the nonce queries (this invocation's receipt label
    must not exist anywhere yet) and the project-label queries must succeed
    and come back empty, each named resource must be absent from successful
    listings, and each trial tag must be absent from a successful image
    listing (a pre-existing tag would be overwritten by the build, which is
    refused instead). The project-label check gates collisions only; it is
    never used as creation evidence.
    """
    problems = []
    for kind in ("container", "volume", "network"):
        proc = _label_query(kind, _nonce_filter(nonce))
        if proc.returncode != 0:
            problems.append(f"nonce {kind} query failed rc={proc.returncode}")
        elif proc.stdout.split():
            problems.append(f"resources already carry this invocation's "
                            f"nonce ({kind}): {proc.stdout.split()}")
        proc = _label_query(kind, f"label={PROJECT_LABEL}={project}")
        if proc.returncode != 0:
            problems.append(f"{kind} project-label query failed "
                            f"rc={proc.returncode}")
        elif proc.stdout.split():
            problems.append(f"project {project} already has {kind}s: "
                            f"{proc.stdout.split()}")
    for name in names:
        for absent in (volume_absent(name), network_absent(name)):
            if not absent[0]:
                problems.append(f"expected-absent resource exists: "
                                f"{absent[1]}")
        named = docker_cli(["ps", "-aq", "--filter", f"name=^/{name}$"])
        if named.returncode != 0:
            problems.append(f"container name query for {name} failed "
                            f"rc={named.returncode}")
        elif named.stdout.split():
            problems.append(f"expected-absent container exists: {name}")
    for ref in tags:
        listed = tag_listed(ref)
        if listed is None:
            problems.append(f"image listing query failed for {ref}")
        elif listed:
            problems.append(f"trial image tag already exists: {ref}")
    return problems


def verify_start_readiness(compose_cfg, capture):
    """Pre-start completeness gate against the FINAL rendered config.

    Every service (measured components, one-shots, and fake-provider
    alike), every declared volume/network, and every volume a receipted
    container actually mounts must carry this run's nonce receipt with a
    COMPLETE, usable identity: containers need their service label and this
    run's nonce, volumes need driver + CreatedAt + matching nonce, networks
    need their immutable Id + matching nonce. Anything missing, unreadable
    (`unverified` receipts), nonce-mismatched, or occupied by a foreign
    object under an expected name forbids start — the caller may then only
    clean the objects this run provably created.
    """
    problems = []
    expected_nonce = capture.get("nonce")
    by_service = {}
    for entry in capture.get("containers", []):
        service = entry.get("service")
        if service is None:
            problems.append(
                f"container {entry['cid'][:12]} receipt lacks a service "
                "identity (inspect failed at capture); cannot prove it")
            continue
        if entry.get("nonce") != expected_nonce:
            problems.append(
                f"container {entry['cid'][:12]} receipt nonce does not match "
                "this run; cannot prove it")
            continue
        if service in by_service:
            problems.append(f"duplicate receipts for service {service}")
        by_service[service] = entry
    services = compose_cfg.get("services", {})
    for svc in services:
        if svc not in by_service:
            problems.append(
                f"service {svc} has no nonce-receipted container; refusing "
                "to start (create incomplete, or the expected name is held "
                "by a foreign object)")
    extra = sorted(set(by_service) - set(services))
    if extra:
        problems.append(f"receipted services outside the rendered config: "
                        f"{extra}")
    receipted_vols = set()
    for entry in capture.get("volumes", []):
        if entry.get("unverified") or entry.get("nonce") != expected_nonce \
                or entry.get("driver") is None \
                or entry.get("created_at") is None:
            problems.append(
                f"volume {entry['name']} receipt unverified or incomplete "
                "(identity unreadable / nonce mismatch); refusing to run "
                "on an unproven volume")
        else:
            receipted_vols.add(entry["name"])
    for key, spec in (compose_cfg.get("volumes") or {}).items():
        name = (spec or {}).get("name")
        if name not in receipted_vols:
            problems.append(f"volume {key} ({name}) has no complete nonce "
                            "receipt; refusing to run on an unproven volume")
    receipted_nets = set()
    for entry in capture.get("networks", []):
        if entry.get("unverified") or entry.get("nonce") != expected_nonce \
                or entry.get("id") is None:
            problems.append(
                f"network {entry['name']} receipt unverified or incomplete "
                "(identity unreadable / nonce mismatch)")
        else:
            receipted_nets.add(entry["name"])
    for key, spec in (compose_cfg.get("networks") or {}).items():
        name = (spec or {}).get("name")
        if name not in receipted_nets:
            problems.append(f"network {key} ({name}) has no complete nonce "
                            "receipt")
    for entry in capture.get("containers", []):
        for mount in entry.get("mounts") or []:
            if mount.get("Type") == "volume" and \
                    mount.get("Name") not in receipted_vols:
                problems.append(
                    f"container {entry.get('name') or entry['cid'][:12]} "
                    f"mounts unproven volume {mount.get('Name')}")
    return problems


def record_built(refs):
    """ref -> actual image Id this run built (None when the tag was never
    produced). Absence is proven by a successful rc0 listing that does not
    carry the ref; a failed listing is UNKNOWN and raises — never mistaken
    for "not built"."""
    ls = docker_cli(["image", "ls", "--format", "{{.Repository}}:{{.Tag}}"])
    if ls.returncode != 0:
        raise RuntimeError(f"image listing query failed rc={ls.returncode}; "
                           "absent vs unknown cannot be distinguished")
    listed = set(ls.stdout.split())
    out = {}
    for ref in refs:
        if ref not in listed:
            out[ref] = None
            continue
        proc = docker_cli(["image", "inspect", ref])
        if proc.returncode != 0:
            raise RuntimeError(f"tag {ref} is listed but inspect failed "
                               f"rc={proc.returncode}; identity unknown")
        try:
            out[ref] = json.loads(proc.stdout)[0]["Id"]
        except (json.JSONDecodeError, IndexError, KeyError) as exc:
            raise RuntimeError(f"image inspect for {ref} unusable: {exc}")
    return out


def untag_if_matching(built):
    """Untag exactly the recorded refs, only while their current identity
    still equals the identity this run built. Never removes by image id, so
    other tags/base images sharing the id are untouched."""
    notes = []
    for ref, image_id in built.items():
        if image_id is None:
            continue
        proc = docker_cli(["image", "inspect", ref])
        if proc.returncode != 0:
            continue  # already untagged/removed
        try:
            current = json.loads(proc.stdout)[0]["Id"]
        except (json.JSONDecodeError, IndexError, KeyError):
            notes.append(f"skip untag {ref}: inspect output unusable")
            continue
        if current != image_id:
            notes.append(f"skip untag {ref}: identity changed "
                         f"({current[:19]} != built {image_id[:19]})")
            continue
        docker_cli(["rmi", ref])
    return notes


def detect_unexpected(project, inventory):
    """Read-only: anything under the project label that is NOT in the
    recorded inventory. Detection only — unexpected entries are reported,
    never removed (their ownership is unproven)."""
    unexpected = {}
    known_cids = {c["cid"] for c in inventory.get("containers", [])}
    ps = _label_query("container", f"label={PROJECT_LABEL}={project}")
    if ps.returncode != 0:
        unexpected["containers"] = [f"label query failed rc={ps.returncode}"]
    else:
        unexpected["containers"] = [c for c in ps.stdout.split()
                                    if c not in known_cids]
    for kind in ("volume", "network"):
        ls = _label_query(kind, f"label={PROJECT_LABEL}={project}")
        if ls.returncode != 0:
            unexpected[kind] = [f"label query failed rc={ls.returncode}"]
        else:
            known = {e["name"] for e in inventory.get(f"{kind}s", [])}
            unexpected[kind] = [n for n in ls.stdout.split() if n not in known]
    return {k: v for k, v in unexpected.items() if v}


def verify_absent(inventory, built):
    """Final absence proof for everything this run created. Every query must
    succeed (rc 0) and not list the resource; failures are problems."""
    problems = []
    for c in inventory.get("containers", []):
        absent, note = container_absent(c["cid"])
        if not absent:
            problems.append(f"container {c['cid'][:12]} not proven gone: {note}")
    vol_names = {e["name"] for e in inventory.get("volumes", [])}
    for name in vol_names:
        absent, note = volume_absent(name)
        if not absent:
            problems.append(f"volume {name} not proven gone: {note}")
    net_names = {e["name"] for e in inventory.get("networks", [])}
    for name in net_names:
        absent, note = network_absent(name)
        if not absent:
            problems.append(f"network {name} not proven gone: {note}")
    for ref, image_id in built.items():
        if image_id is None:
            continue
        listed = tag_listed(ref)
        if listed is None:
            problems.append(f"image listing query failed for {ref}")
        elif listed:
            problems.append(f"trial tag still listed: {ref}")
    return problems


def _load_json(path):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None


def _load_state(path):
    """('missing', None) when absent, ('unknown', reason) when present but
    unreadable/corrupt or not a JSON object, ('ok', dict) otherwise.

    The distinction matters: an explicit valid (possibly empty) record is a
    real answer, while missing/unknown records must never be folded into an
    empty success — resources created before the record was lost stay
    unproven and the caller must keep every recovery clue.
    """
    if not os.path.exists(path):
        return "missing", None
    try:
        with open(path) as fh:
            data = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        return "unknown", f"{type(exc).__name__}"
    if not isinstance(data, dict):
        return "unknown", "record is not a JSON object"
    return "ok", data


def _write_json(path, data):
    with open(path, "w") as fh:
        json.dump(data, fh, indent=1)
        fh.write("\n")


def cleanup_recorded(capture, built, collectors, leftovers_out, project=None,
                     unknown=()):
    """One actual exit path for everything this run created.

    Order: collector containers (exact CIDs from this run's launch record),
    then recorded stack containers, volumes, networks, then trial tags —
    each identity-checked before removal. A read-only detector reports any
    project-labelled resource outside the records, and a final absence
    proof turns query failures into visible leftovers. Returns the number
    of problem categories (0 = provably clean).

    `unknown` carries CLI-level facts that a REQUIRED receipt record
    (capture/built; collectors only when present-but-unreadable) is missing
    or unreadable: receipts that ARE confirmed still get cleaned by their
    exact identities, but the run can never report clean, and the caller
    must keep the original records/nonce/config for recovery — never treat
    the unconfirmed remainder as an empty success.
    """
    capture = capture or {"containers": [], "volumes": [], "networks": []}
    built = built or {}
    leftovers = {"containers": [], "volumes": [], "networks": [],
                 "images": [], "unverified": list(unknown),
                 "unexpected_labelled": {}}
    leftovers["containers"] += stop_remove_containers(
        (collectors or {}).get("containers", []))
    leftovers["containers"] += stop_remove_containers(
        capture.get("containers", []))
    project = project or capture.get("project") or \
        (collectors or {}).get("project")
    if project:
        expected_nonce = capture.get("nonce")
        leftovers["volumes"] += _remove_named("volume",
                                              capture.get("volumes", []),
                                              expected_nonce)
        leftovers["networks"] += _remove_named("network",
                                               capture.get("networks", []),
                                               expected_nonce)
        leftovers["unexpected_labelled"] = detect_unexpected(project, capture)
    leftovers["images"] += untag_if_matching(built)
    leftovers["unverified"] += verify_absent(capture, built)
    leftovers = {k: v for k, v in leftovers.items() if v}
    if leftovers_out:
        _write_json(leftovers_out, leftovers)
    for category, items in leftovers.items():
        for item in (items if isinstance(items, list) else [items]):
            print(f"cleanup leftover [{category}]: {item}", file=sys.stderr)
    return len(leftovers)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("require-absent",
                       help="preflight absence proof (nonce, label, names, tags)")
    p.add_argument("--project", required=True)
    p.add_argument("--nonce", required=True)
    p.add_argument("--name", action="append", default=[])
    p.add_argument("--tag", action="append", default=[])

    p = sub.add_parser("capture",
                       help="record this run's nonce-receipted inventory "
                            "between create and start")
    p.add_argument("--project", required=True)
    p.add_argument("--nonce", required=True)
    p.add_argument("--out", required=True)

    p = sub.add_parser("verify-start",
                       help="pre-start gate: every rendered service, "
                            "volume, network, and actual mount must carry "
                            "this run's nonce receipt")
    p.add_argument("--compose", required=True)
    p.add_argument("--capture", required=True)

    p = sub.add_parser("record-built",
                       help="record actual image identities after build")
    p.add_argument("--out", required=True)
    p.add_argument("refs", nargs="+")

    p = sub.add_parser("cleanup",
                       help="remove exactly the recorded resources and prove "
                            "absence; exits nonzero on any leftover")
    p.add_argument("--capture", required=True)
    p.add_argument("--built", required=True)
    p.add_argument("--collectors", required=True)
    p.add_argument("--leftovers-out", required=True)
    p.add_argument("--project", default="",
                   help="project for the read-only detector when no capture "
                        "record could be written")
    p.add_argument("--collectors-required", choices=("yes", "no"),
                   default="no",
                   help="yes = the collector launch was attempted this run: "
                        "a missing (not just unreadable) collectors record "
                        "is unverified — helpers created before the record "
                        "was lost must never fold into an empty success")
    p.add_argument("--deadline-seconds", type=float, default=0,
                   help="wall-clock bound for every docker call in THIS "
                        "cleanup (0 = unbounded, the G12 default); expiry "
                        "exits nonzero so the caller keeps the records")

    args = ap.parse_args()
    global _DEADLINE_MONO
    if args.cmd == "cleanup" and args.deadline_seconds > 0:
        _DEADLINE_MONO = time.monotonic() + args.deadline_seconds
    if args.cmd == "require-absent":
        problems = require_absent(args.project, args.nonce, args.name, args.tag)
        for problem in problems:
            print(f"preflight: {problem}", file=sys.stderr)
        return 1 if problems else 0
    if args.cmd == "capture":
        inv = capture_inventory(args.nonce, args.project)
        _write_json(args.out, inv)
        print(f"  captured {len(inv['containers'])} containers, "
              f"{len(inv['volumes'])} volumes, {len(inv['networks'])} "
              f"networks -> {args.out}", file=sys.stderr)
        return 0
    if args.cmd == "record-built":
        _write_json(args.out, record_built(args.refs))
        return 0
    if args.cmd == "verify-start":
        compose_cfg = _load_json(args.compose) or {}
        capture = _load_json(args.capture) or {}
        problems = verify_start_readiness(compose_cfg, capture)
        for problem in problems:
            print(f"start gate: {problem}", file=sys.stderr)
        return 1 if problems else 0
    states = {name: _load_state(path) for name, path in
              (("capture", args.capture), ("built", args.built),
               ("collectors", args.collectors))}
    unknown = []
    for name in ("capture", "built"):
        state, reason = states[name]
        if state != "ok":
            detail = "missing" if state == "missing" else f"unreadable ({reason})"
            unknown.append(f"{name} receipt record {detail}; created-but-"
                           "unrecorded resources may exist and are not "
                           "proven cleaned")
    if states["collectors"][0] == "unknown":
        unknown.append(f"collectors record unreadable "
                       f"({states['collectors'][1]}); helper containers "
                       "recorded before the corruption are not proven "
                       "cleaned")
    elif (args.collectors_required == "yes"
          and states["collectors"][0] == "missing"):
        unknown.append("collectors receipt record missing although the "
                       "launch was attempted this run; helpers created "
                       "before the record was lost are not proven cleaned")
    return 1 if cleanup_recorded(
        states["capture"][1] if states["capture"][0] == "ok" else None,
        states["built"][1] if states["built"][0] == "ok" else None,
        states["collectors"][1] if states["collectors"][0] == "ok" else None,
        args.leftovers_out, project=args.project or None,
        unknown=unknown) else 0


if __name__ == "__main__":
    sys.exit(main())
